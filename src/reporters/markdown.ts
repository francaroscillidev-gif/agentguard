import { ManifestAuditReport, ManifestAuditItem } from '../checkers/manifests.js';
import { SecretAuditReport, SecretLeakDetection } from '../checkers/secrets.js';
import { AdvancedSmellReport, CodeSmell } from '../checkers/smells.js';
import { SlopAnalysisReport } from '../checkers/slop.js';
import { PromptInjectionReport, PromptInjectionDetection } from '../checkers/injections.js';

export interface ComprehensiveAuditData {
  manifests?: ManifestAuditReport;
  secrets?: SecretAuditReport;
  injections?: PromptInjectionReport;
  smells?: AdvancedSmellReport;
  slop?: SlopAnalysisReport;
}

export function generateFullMarkdownReport(data: ComprehensiveAuditData): string {
  const parts: string[] = [];

  parts.push(`# 🛡️ AgentGuard Comprehensive Audit Report`);
  parts.push(`Generated by **AgentGuard Sentinel** for AI-generated code, security, and integrity.\n`);

  // 1. Dependency Hallucination
  if (data.manifests) {
    const passed = data.manifests.passed;
    const badge = passed ? '✅ PASSED' : '❌ FAILED';
    parts.push(`## 📦 1. Supply Chain & Dependency Verification (${badge})`);
    parts.push(`- **Scanned Manifests:** ${data.manifests.scannedFiles.length}`);
    parts.push(`- **Total Dependencies:** ${data.manifests.totalDependencies}`);
    parts.push(`- **Hallucinations Detected:** ${data.manifests.hallucinatedCount}`);
    parts.push(`- **High Risk Packages:** ${data.manifests.highRiskCount}\n`);

    if (data.manifests.hallucinatedCount > 0) {
      parts.push(`> [!CAUTION]\n> Hallucinated packages detected in project manifests:\n`);
      data.manifests.dependencies
        .filter((d: ManifestAuditItem) => d.result.isHallucinated)
        .forEach((d: ManifestAuditItem) => {
          parts.push(`- \`${d.name}\` (in \`${d.file}\`)`);
        });
      parts.push('');
    }
  }

  // 2. Secret Leaks
  if (data.secrets) {
    const passed = data.secrets.passed;
    const badge = passed ? '✅ NO LEAKS' : '🚨 LEAKS DETECTED';
    parts.push(`## 🔑 2. Secrets & Credential Interception (${badge})`);
    parts.push(`- **Total Exposed Secrets:** ${data.secrets.totalLeaks}\n`);

    if (data.secrets.totalLeaks > 0) {
      parts.push(`| File:Line | Credential Type | Snippet |`);
      parts.push(`|---|---|---|`);
      data.secrets.detections.forEach((d: SecretLeakDetection) => {
        parts.push(`| \`${d.filePath}:${d.line}\` | ${d.patternType} | \`${d.snippet}\` |`);
      });
      parts.push('');
    }
  }

  // 3. Indirect Prompt Injection Vectors
  if (data.injections) {
    const passed = data.injections.passed;
    const badge = passed ? '✅ SECURE' : '🚨 PROMPT INJECTIONS DETECTED';
    parts.push(`## 🎯 3. Indirect Prompt Injection & Jailbreak Defense (${badge})`);
    parts.push(`- **Total Vectors Found:** ${data.injections.totalDetections}\n`);

    if (data.injections.totalDetections > 0) {
      parts.push(`| File:Line | Threat Type | Snippet |`);
      parts.push(`|---|---|---|`);
      data.injections.detections.forEach((d: PromptInjectionDetection) => {
        parts.push(`| \`${d.filePath}:${d.line}\` | ${d.patternType} | \`${d.snippet}\` |`);
      });
      parts.push('');
    }
  }

  // 4. AI Code Smells
  if (data.smells) {
    const badge = data.smells.totalSmells === 0 ? '✅ CLEAN' : `⚠️ ${data.smells.totalSmells} SMELLS`;
    parts.push(`## 🦹 4. AI Code Smells & Antipatterns (${badge})`);
    parts.push(`- **Total Code Smells:** ${data.smells.totalSmells}\n`);

    if (data.smells.totalSmells > 0) {
      parts.push(`| File:Line | Antipattern | Severity | Recommendation |`);
      parts.push(`|---|---|---|---|`);
      data.smells.smells.forEach((s: CodeSmell) => {
        parts.push(`| \`${s.filePath}:${s.line}\` | ${s.type} | **${s.severity.toUpperCase()}** | ${s.recommendation} |`);
      });
      parts.push('');
    }
  }

  // 5. Slop & Boilerplate
  if (data.slop) {
    const badge = data.slop.passed ? '✅ OPTIMIZED' : `⚠️ ${data.slop.totalIssues} ISSUES`;
    parts.push(`## 🧹 5. AI Slop & Repetitive Utility Audit (${badge})`);
    parts.push(`- **Total Boilerplate Issues:** ${data.slop.totalIssues}\n`);
  }

  return parts.join('\n');
}
